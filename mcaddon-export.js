    function createPackIcon(label) {
        const canvas = document.createElement("canvas");
        canvas.width = 256;
        canvas.height = 256;

        const ctx = canvas.getContext("2d");

        const gradient = ctx.createLinearGradient(0, 0, 256, 256);
        gradient.addColorStop(0, "#161616");
        gradient.addColorStop(0.5, "#5b167f");
        gradient.addColorStop(1, "#d20077");

        ctx.fillStyle = gradient;
        ctx.fillRect(0, 0, 256, 256);

        ctx.fillStyle = "rgba(255,255,255,.11)";
        for (let y = 0; y < 256; y += 32) {
            for (let x = (y / 32) % 2 ? 16 : 0; x < 256; x += 32) {
                ctx.fillRect(x, y, 16, 16);
            }
        }

        ctx.strokeStyle = "rgba(255,255,255,.8)";
        ctx.lineWidth = 8;
        ctx.strokeRect(12, 12, 232, 232);

        ctx.textAlign = "center";
        ctx.textBaseline = "middle";
        ctx.fillStyle = "#fff";
        ctx.font = "bold 58px sans-serif";
        ctx.fillText("RAG", 128, 104);

        ctx.font = "bold 25px sans-serif";
        ctx.fillText("UI PREVIEW", 128, 158);

        ctx.font = "16px sans-serif";
        const shortLabel = String(label).slice(0, 22);
        ctx.fillText(shortLabel, 128, 198);

        return new Promise((resolve, reject) => {
            canvas.toBlob((blob) => {
                if (blob) resolve(blob);
                else reject(new Error("Nao foi possivel gerar pack_icon.png"));
            }, "image/png");
        });
    }

    async function imageDataToPngBlob(imageData) {
        const canvas = document.createElement("canvas");
        canvas.width = imageData.width;
        canvas.height = imageData.height;
        canvas.getContext("2d").putImageData(imageData, 0, 0);

        return new Promise((resolve, reject) => {
            canvas.toBlob((blob) => {
                if (blob) resolve(blob);
                else reject(new Error("Falha ao converter textura para PNG"));
            }, "image/png");
        });
    }

    function normalizedTexturePath(key, extension) {
        let path = String(key)
            .replace(/^textures\//, "")
            .replace(/\.(png|jpg|jpeg|webp|tga|json)$/i, "")
            .replace(/^\/+/, "");

        return `textures/${path}.${extension}`;
    }

    async function addLoadedEditorTextures(files, rpRoot, images) {
        let count = 0;

        for (const [key, state] of images.entries()) {
            if (!state) continue;

            if (state.png) {
                const blob = await imageDataToPngBlob(state.png);
                files.set(
                    `${rpRoot}/${normalizedTexturePath(key, "png")}`,
                    blob
                );
                count++;
            }

            if (state.json) {
                files.set(
                    `${rpRoot}/${normalizedTexturePath(key, "json")}`,
                    JSON.stringify(state.json, null, 4)
                );
            }
        }

        return count;
    }

    async function fetchBlobChecked(url) {
        const response = await fetch(url, { cache: "no-store" });
        if (!response.ok) {
            throw new Error(`${response.status} ${response.statusText}: ${url}`);
        }
        return response.blob();
    }

    async function fetchJsonChecked(url) {
        const response = await fetch(url, { cache: "no-store" });
        if (!response.ok) {
            throw new Error(`${response.status} ${response.statusText}: ${url}`);
        }
        return response.json();
    }

    async function addBuiltinTextureSets(files, rpRoot, onProgress) {
        let count = 0;
        const warnings = [];

        for (let setIndex = 0; setIndex < BUILTIN_TEXTURE_SETS.length; setIndex++) {
            const setName = BUILTIN_TEXTURE_SETS[setIndex];

            onProgress?.(
                `Incluindo texturas ${setName.replace("_ore-ui_style", "")}...`
            );

            try {
                const mapping = await fetchJsonChecked(
                    `presets/textures/${setName}/mapping.json`
                );

                const entries = Array.isArray(mapping?.data) ? mapping.data : [];

                for (const entry of entries) {
                    const image = entry?.image;
                    if (!image) continue;

                    try {
                        const png = await fetchBlobChecked(
                            `presets/textures/${setName}/${image}.png`
                        );

                        files.set(
                            `${rpRoot}/textures/presets/textures/${setName}/${image}.png`,
                            png
                        );
                        count++;

                        if (entry.nineslice) {
                            const json = await fetchJsonChecked(
                                `presets/textures/${setName}/${image}.json`
                            );

                            files.set(
                                `${rpRoot}/textures/presets/textures/${setName}/${image}.json`,
                                JSON.stringify(json, null, 4)
                            );
                        }
                    } catch (error) {
                        warnings.push(String(error));
                    }
                }
            } catch (error) {
                warnings.push(String(error));
            }
        }

        return { count, warnings };
    }

