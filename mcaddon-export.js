/**
 * JSON-UI Maker - MCADDON Preview Exporter
 *
 * Exports the current editor project as a ready-to-import .mcaddon:
 *   - Resource Pack: generated JSON UI + server_form bridge + textures
 *   - Behavior Pack: /scriptevent rag:<name> preview command
 *
 * Built-in texture sets bundled automatically:
 *   eternal, other, pink, red, turquoise
 *
 * No external ZIP library is required. The exporter writes an uncompressed ZIP
 * directly in the browser, which Minecraft accepts as .mcaddon.
 */
