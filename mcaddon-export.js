    // ---------- Tiny ZIP writer (STORE / no compression) ----------

    const CRC_TABLE = (() => {
        const table = new Uint32Array(256);

        for (let n = 0; n < 256; n++) {
            let c = n;

            for (let k = 0; k < 8; k++) {
                c = (c & 1) ? (0xedb88320 ^ (c >>> 1)) : (c >>> 1);
            }

            table[n] = c >>> 0;
        }

        return table;
    })();

    function crc32(bytes) {
        let crc = 0xffffffff;

        for (let i = 0; i < bytes.length; i++) {
            crc = CRC_TABLE[(crc ^ bytes[i]) & 0xff] ^ (crc >>> 8);
        }

        return (crc ^ 0xffffffff) >>> 0;
    }

    function dosTimeDate(date = new Date()) {
        const year = Math.max(1980, date.getFullYear());

        const time =
            (date.getHours() << 11) |
            (date.getMinutes() << 5) |
            Math.floor(date.getSeconds() / 2);

        const dosDate =
            ((year - 1980) << 9) |
            ((date.getMonth() + 1) << 5) |
            date.getDate();

        return { time, date: dosDate };
    }

    function u16(view, offset, value) {
        view.setUint16(offset, value, true);
    }

    function u32(view, offset, value) {
        view.setUint32(offset, value >>> 0, true);
    }

    async function toBytes(value) {
        if (value instanceof Uint8Array) return value;
        if (value instanceof ArrayBuffer) return new Uint8Array(value);
        if (value instanceof Blob) return new Uint8Array(await value.arrayBuffer());
        return textEncoder.encode(String(value));
    }

    function concatUint8(parts) {
        const total = parts.reduce((sum, p) => sum + p.length, 0);
        const output = new Uint8Array(total);
        let offset = 0;

        for (const part of parts) {
            output.set(part, offset);
            offset += part.length;
        }

        return output;
    }

    async function makeZip(fileMap) {
        const localParts = [];
        const centralParts = [];
        let localOffset = 0;
        let entries = 0;

        const { time, date } = dosTimeDate();

        for (const [rawName, value] of fileMap.entries()) {
            const name = rawName.replace(/\\/g, "/").replace(/^\/+/, "");
            const nameBytes = textEncoder.encode(name);
            const data = await toBytes(value);
            const crc = crc32(data);

            const localHeader = new Uint8Array(30);
            const lv = new DataView(localHeader.buffer);

            u32(lv, 0, 0x04034b50);
            u16(lv, 4, 20);
            u16(lv, 6, 0x0800); // UTF-8
            u16(lv, 8, 0); // STORE
            u16(lv, 10, time);
            u16(lv, 12, date);
            u32(lv, 14, crc);
            u32(lv, 18, data.length);
            u32(lv, 22, data.length);
            u16(lv, 26, nameBytes.length);
            u16(lv, 28, 0);

            localParts.push(localHeader, nameBytes, data);

            const central = new Uint8Array(46);
            const cv = new DataView(central.buffer);

            u32(cv, 0, 0x02014b50);
            u16(cv, 4, 20);
            u16(cv, 6, 20);
            u16(cv, 8, 0x0800);
            u16(cv, 10, 0);
            u16(cv, 12, time);
            u16(cv, 14, date);
            u32(cv, 16, crc);
            u32(cv, 20, data.length);
            u32(cv, 24, data.length);
            u16(cv, 28, nameBytes.length);
            u16(cv, 30, 0);
            u16(cv, 32, 0);
            u16(cv, 34, 0);
            u16(cv, 36, 0);
            u32(cv, 38, 0);
            u32(cv, 42, localOffset);

            centralParts.push(central, nameBytes);

            localOffset += localHeader.length + nameBytes.length + data.length;
            entries++;
        }

        const centralBytes = concatUint8(centralParts);
        const end = new Uint8Array(22);
        const ev = new DataView(end.buffer);

        u32(ev, 0, 0x06054b50);
        u16(ev, 4, 0);
        u16(ev, 6, 0);
        u16(ev, 8, entries);
        u16(ev, 10, entries);
        u32(ev, 12, centralBytes.length);
        u32(ev, 16, localOffset);
        u16(ev, 20, 0);

        return new Blob(
            [...localParts, centralBytes, end],
            { type: "application/zip" }
        );
    }

    function downloadBlob(blob, filename) {
        const url = URL.createObjectURL(blob);
        const a = document.createElement("a");

        a.href = url;
        a.download = filename;
        document.body.appendChild(a);
        a.click();
        a.remove();

        setTimeout(() => URL.revokeObjectURL(url), 5000);
    }

    function setStatus(modal, text, kind = "normal") {
        const status = modal.querySelector(".rag-export-status");
        if (!status) return;

        status.textContent = text;
        status.dataset.kind = kind;
    }

    async function exportMcaddon(modal, rawName) {
        const { index, config, JSON_TYPES_GENERATOR, Converter } =
            await loadEditorModules();

        const eventName = sanitizeIdentifier(rawName);
        const packDisplayName = `RAG UI PREVIEW - ${eventName}`;
        const fileBase = sanitizeFileName(`RAG_UI_${eventName}`);

        const mainWindow = document.getElementById("main_window");
        if (!mainWindow) {
            throw new Error("main_window nao encontrado.");
        }

        if (!config.rootElement) {
            throw new Error("Crie/carregue um form antes de exportar.");
        }

        setStatus(modal, "Gerando JSON UI...");

        const rawUi = Converter.convertToJsonUi(index.panelContainer, 0);
        const gameUi = makeGameUiJson(rawUi);

        const namespace = config.nameSpace;
        const titleFlag = config.title_flag;

        const serverFormGenerator = JSON_TYPES_GENERATOR.get("server_form");
        if (!serverFormGenerator) {
            throw new Error("Gerador server_form nao encontrado.");
        }

        const serverForm = serverFormGenerator(namespace);
        const previewButtons = getButtonPreviewData(mainWindow);

        const rpHeaderUuid = uuid();
        const rpModuleUuid = uuid();
        const bpHeaderUuid = uuid();
        const bpDataUuid = uuid();
        const bpScriptUuid = uuid();

        const rpRoot = `${fileBase}_RP`;
        const bpRoot = `${fileBase}_BP`;

        const files = new Map();

        files.set(
            `${rpRoot}/manifest.json`,
            createResourceManifest(packDisplayName, rpHeaderUuid, rpModuleUuid)
        );

        files.set(
            `${bpRoot}/manifest.json`,
            createBehaviorManifest(
                packDisplayName,
                bpHeaderUuid,
                bpDataUuid,
                bpScriptUuid,
                rpHeaderUuid
            )
        );

        const packIcon = await createPackIcon(eventName);
        files.set(`${rpRoot}/pack_icon.png`, packIcon);
        files.set(`${bpRoot}/pack_icon.png`, packIcon);

        files.set(`${rpRoot}/ui/${namespace}.json`, gameUi);
        files.set(`${rpRoot}/ui/server_form.json`, serverForm);
        files.set(`${rpRoot}/ui/_ui_defs.json`, makeUiDefs(namespace));

        files.set(
            `${bpRoot}/scripts/main.js`,
            generatePreviewScript(eventName, titleFlag, previewButtons)
        );

        setStatus(modal, "Incluindo texturas carregadas no editor...");

        const loadedTextureCount = await addLoadedEditorTextures(
            files,
            rpRoot,
            index.images
        );

        const builtin = await addBuiltinTextureSets(
            files,
            rpRoot,
            (message) => setStatus(modal, message)
        );

        const totalTextures = loadedTextureCount + builtin.count;
        const command = `/scriptevent rag:${eventName}`;

        files.set(
            `${fileBase}_LEIA-ME.txt`,
            makePreviewReadme(command, namespace, titleFlag, totalTextures)
        );

        files.set(
            `${bpRoot}/PREVIEW_COMMAND.txt`,
            `${command}\n`
        );

        setStatus(
            modal,
            `Empacotando ${files.size} arquivos (${totalTextures} texturas)...`
        );

        const zip = await makeZip(files);

        downloadBlob(zip, `${fileBase}.mcaddon`);

        if (builtin.warnings.length) {
            console.warn(
                "[RAG MCADDON Export] Algumas texturas de preset nao puderam ser baixadas:",
                builtin.warnings
            );
        }

        setStatus(
            modal,
            `Pronto! Teste no Minecraft com: ${command}`,
            "success"
        );

        const commandBox = modal.querySelector(".rag-export-command");
        if (commandBox) commandBox.textContent = command;
    }

