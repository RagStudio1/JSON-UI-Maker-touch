    function uuid() {
        if (crypto.randomUUID) return crypto.randomUUID();

        const b = new Uint8Array(16);
        crypto.getRandomValues(b);
        b[6] = (b[6] & 0x0f) | 0x40;
        b[8] = (b[8] & 0x3f) | 0x80;

        return [...b]
            .map((v, i) =>
                ([4, 6, 8, 10].includes(i) ? "-" : "") +
                v.toString(16).padStart(2, "0")
            )
            .join("");
    }

    function sanitizeIdentifier(value) {
        let s = String(value ?? "")
            .normalize("NFD")
            .replace(/[\u0300-\u036f]/g, "")
            .toLowerCase()
            .replace(/[^a-z0-9_.-]+/g, "_")
            .replace(/^[_\-.]+|[_\-.]+$/g, "");

        if (!s) s = "preview";
        return s.slice(0, 48);
    }

    function sanitizeFileName(value) {
        let s = String(value ?? "")
            .normalize("NFD")
            .replace(/[\u0300-\u036f]/g, "")
            .replace(/[<>:"/\\|?*\u0000-\u001f]+/g, "_")
            .replace(/\s+/g, "_")
            .replace(/^_+|_+$/g, "");

        if (!s) s = "RAG_UI_PREVIEW";
        return s.slice(0, 80);
    }

    function stripGeneratedComment(jsonText) {
        return String(jsonText).replace(
            /\s*\/\*\s*Generated by JSON-UI Maker[\s\S]*?\*\/\s*$/i,
            ""
        );
    }

