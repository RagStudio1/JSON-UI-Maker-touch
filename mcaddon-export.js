    function getButtonPreviewData(mainWindow) {
        const buttons = [...mainWindow.querySelectorAll(".draggable-button[data-collection-index]")];

        const byIndex = new Map();

        for (const button of buttons) {
            const index = Number(button.dataset.collectionIndex);
            if (!Number.isInteger(index) || index < 0) continue;

            const nestedLabel = button.querySelector("textarea.draggable-label");
            const nestedCanvas = [...button.querySelectorAll(".draggable-canvas[data-image-path]")]
                .find((el) => el.dataset.shouldParse === "false") ||
                button.querySelector(".draggable-canvas[data-image-path]");

            const text =
                nestedLabel?.value?.trim() ||
                button.dataset.displayText?.trim() ||
                `BOTAO ${index + 1}`;

            const imagePath =
                nestedCanvas?.dataset.imagePath?.trim() ||
                button.dataset.displayImagePath?.trim() ||
                "";

            byIndex.set(index, {
                text,
                imagePath,
            });
        }

        if (byIndex.size === 0) {
            return [{ text: "PREVIEW", imagePath: "" }];
        }

        const maxIndex = Math.max(...byIndex.keys());
        const result = [];

        for (let i = 0; i <= maxIndex; i++) {
            result.push(
                byIndex.get(i) || {
                    text: `PREVIEW ${i + 1}`,
                    imagePath: "",
                }
            );
        }

        return result;
    }

    function generatePreviewScript(eventName, titleFlag, buttons) {
        const eventId = `rag:${eventName}`;

        const serializedButtons = JSON.stringify(
            buttons.map((button) => ({
                text: button.text,
                imagePath: button.imagePath
                    ? `textures/${button.imagePath.replace(/^textures\//, "")}`
                    : "",
            })),
            null,
            4
        );

        return `import { system, Player } from "@minecraft/server";
import { ActionFormData } from "@minecraft/server-ui";

const EVENT_ID = ${JSON.stringify(eventId)};
const TITLE_FLAG = ${JSON.stringify(titleFlag)};
const BUTTONS = ${serializedButtons};

async function showPreview(player) {
    const form = new ActionFormData()
        .title(TITLE_FLAG);

    for (const button of BUTTONS) {
        if (button.imagePath) {
            form.button(button.text, button.imagePath);
        } else {
            form.button(button.text);
        }
    }

    try {
        const response = await form.show(player);

        if (!response.canceled && response.selection !== undefined) {
            player.sendMessage(\`§a[RAG Preview] §fBotao selecionado: §e\${response.selection}\`);
        }
    } catch (error) {
        player.sendMessage(\`§c[RAG Preview] Falha ao abrir o form: \${error}\`);
    }
}

system.afterEvents.scriptEventReceive.subscribe((event) => {
    if (event.id !== EVENT_ID) return;

    const player = event.sourceEntity;

    if (!(player instanceof Player)) {
        return;
    }

    // Defer one tick so the form is opened outside the event callback itself.
    system.run(() => {
        showPreview(player);
    });
});
`;
    }

